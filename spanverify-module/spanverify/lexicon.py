def find_phrase_hits(words: list[str]) -> set[int]:
    """Индексы токенов, входящих в найденные шаблонные обороты.

    Поиск идёт по нормализованным словоформам, максимальное совпадение —
    самое длинное (от 4 слов к 2), чтобы не дублировать вхождения.
    """
    normal = [w.lower().replace("ё", "е") for w in words]
    hits: set[int] = set()
    length = len(normal)
    for size in (4, 3, 2):
        for i in range(length - size + 1):
            if i in hits:
                continue
            gram = tuple(normal[i : i + size])
            if gram in CLICHE_PHRASES:
                hits.update(range(i, i + size))
    return hits
