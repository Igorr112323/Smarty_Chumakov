"""Предельные размеры входа и выхода — единый источник чисел договора.

Договор № ____ГУ/2026 (проект 117812), ТЗ п. 4.1 устанавливает:

* требование 1 — вход: текст в UTF-8, максимальная длина обрабатываемого текста
  **2 000 000 знаков**;
* требование 7 — быстродействие: не более 0.03 с на 1 000 знаков, 2 000 000
  знаков — не более 60 с;
* требование 8 — интерфейсы: командная строка, локальный веб-интерфейс,
  HTTP API.

Модуль держит эти величины в одном месте, чтобы командная строка, HTTP API и
контрольные проверки пользовались одним и тем же лимитом, а не «своими»
константами. Значение лимита менять нельзя — это требование договора; можно
только исполнять его.
"""

from __future__ import annotations

from collections.abc import Sequence

__all__ = [
    "LIMIT_BYTES_PER_SECOND_KB",
    "MAX_REQUEST_BYTES",
    "MAX_TEXT_CHARS",
    "MIN_PYTHON",
    "TARGET_MS_PER_1000_CHARS",
    "TARGET_SECONDS_2M",
    "check_text_length",
    "text_ok",
]

#: Максимальная длина одного текста (ответа или документа-источника), знаков.
MAX_TEXT_CHARS = 2_000_000

#: Целевое быстродействие: не более 0.03 с на 1 000 знаков.
TARGET_MS_PER_1000_CHARS = 30.0

#: Целевое время обработки предельного текста 2 000 000 знаков.
TARGET_SECONDS_2M = 60.0

#: Служебная величина для отчётов: сколько знаков в секунду соответствует цели.
LIMIT_BYTES_PER_SECOND_KB = 1000.0 / (TARGET_MS_PER_1000_CHARS / 1000.0)

#: Ограничение тела HTTP-запроса. Два текста по 2 000 000 знаков в UTF-8 — это
#: до 8 МБ (русская буква — 2 байта) плюс JSON-обвязка, поэтому 16 МБ.
MAX_REQUEST_BYTES = 16 * 1024 * 1024

#: Минимальная поддерживаемая версия Python (требование 9: пакет для 3.10+).
MIN_PYTHON = (3, 10)


class TextTooLongError(ValueError):
    """Текст длиннее предельного размера (ТЗ п. 4.1, требование 1)."""


def text_ok(text: str, limit: int = MAX_TEXT_CHARS) -> bool:
    """Уложится ли текст в лимит знаков."""
    return len(text) <= limit


def check_text_length(texts: Sequence[str] | str, limit: int = MAX_TEXT_CHARS) -> None:
    """Проверить длину текста (или нескольких текстов) и объяснить отказ.

    Ошибка называет фактическую длину, лимит и требование договора — чтобы
    пользователь видел причину отказа, а не «ошибка 400» без подробностей.
    """
    items = [texts] if isinstance(texts, str) else list(texts)
    for index, text in enumerate(items):
        if len(text) <= limit:
            continue
        where = "ответ" if index == 0 else "документ-источник"
        raise TextTooLongError(
            f"{where}: {len(text)} знаков, предел {limit} знаков "
            f"(договор № ____ГУ/2026, ТЗ п. 4.1 треб. 1: максимум {MAX_TEXT_CHARS} знаков). "
            "Сократите текст или разбейте его на части."
        )
